/* eslint-disable shadcn/no-unknown-classes, shadcn/no-raw-colors -- print
   artwork is a standalone print document styled by the stylesheet in
   utils/print/print-document.server.tsx, not by Tailwind. */
import {
	type PrintArtworkCopy,
	type PrintPiece,
	type PrintSnapshot,
} from '@repo/common/print-shop'
import { printCatalog } from '@repo/common/print-shop-catalog'

/**
 * One printed piece, rendered to static HTML for the proof and the PDF. It
 * uses only class names: sizes, colors and fonts come from the document
 * stylesheet (`print-document.server.ts`), so the same markup serves the
 * on-screen proof, the home sheet and the professional file.
 */
export function PrintArtwork({
	snapshot,
	piece,
	qrSvg,
}: {
	snapshot: PrintSnapshot
	piece: PrintPiece
	/** Inline SVG markup of the QR code (generated server-side), or null. */
	qrSvg: string | null
}) {
	const product = printCatalog.products[snapshot.product]
	const [main, second] = snapshot.copy
	if (!main || !product) return null
	const family = product.family
	const featured = product.featuredItems ? snapshot.featured : []
	return (
		<section
			className={`piece family-${family} style-${snapshot.style}`}
			dir={main.dir}
			lang={main.locale}
		>
			<div className="bg" aria-hidden="true" />
			<div className="safe">
				<header className="brand">
					{snapshot.brand.logoDataUri ? (
						<img className="logo" src={snapshot.brand.logoDataUri} alt="" />
					) : null}
					<span className="brand-name">{snapshot.brand.name}</span>
				</header>

				{piece.label ? (
					<div className="piece-label">
						<Bilingual
							main={main}
							second={second}
							pick={(copy) =>
								copy.pieceWord
									? `${copy.pieceWord} ${piece.label}`
									: piece.label!
							}
						/>
					</div>
				) : null}

				<div className="message">
					<h1 className="headline">
						<Bilingual main={main} second={second} pick={(c) => c.headline} />
					</h1>
					{main.body ? (
						<p className="body">
							<Bilingual main={main} second={second} pick={(c) => c.body} />
						</p>
					) : null}
				</div>

				{featured.length > 0 ? (
					<ul className={`featured featured-${featured.length}`}>
						{featured.map((item) => (
							<li key={item.id} className="featured-item">
								{item.imageDataUri ? (
									<img
										className="featured-image"
										src={item.imageDataUri}
										alt=""
									/>
								) : (
									<span className="featured-image featured-blank" />
								)}
								<span className="featured-name">{item.name}</span>
								<span className="featured-price" dir="ltr">
									{item.price}
								</span>
							</li>
						))}
					</ul>
				) : null}

				{qrSvg ? (
					<figure className="qr">
						<div
							className="qr-code"
							// Generated by `qrcode` from our own URL, never user markup.
							dangerouslySetInnerHTML={{ __html: qrSvg }}
						/>
						<figcaption className="qr-caption">
							<Bilingual
								main={main}
								second={second}
								pick={(c) => c.qrCaption}
							/>
						</figcaption>
					</figure>
				) : null}

				{main.callToAction ? (
					<p className="cta">
						<Bilingual
							main={main}
							second={second}
							pick={(c) => c.callToAction}
						/>
					</p>
				) : null}

				{snapshot.address || snapshot.website ? (
					<footer className="footer">
						{snapshot.address ? (
							<span className="footer-address">{snapshot.address}</span>
						) : null}
						{snapshot.website ? (
							<span className="footer-website" dir="ltr">
								{snapshot.website}
							</span>
						) : null}
					</footer>
				) : null}
			</div>
		</section>
	)
}

function Bilingual({
	main,
	second,
	pick,
}: {
	main: PrintArtworkCopy
	second: PrintArtworkCopy | undefined
	pick: (copy: PrintArtworkCopy) => string
}) {
	const mainText = pick(main)
	const secondText = second ? pick(second) : ''
	return (
		<>
			<span className="text-main" lang={main.locale} dir={main.dir}>
				{mainText}
			</span>
			{secondText && secondText !== mainText ? (
				<span className="text-second" lang={second!.locale} dir={second!.dir}>
					{secondText}
				</span>
			) : null}
		</>
	)
}
