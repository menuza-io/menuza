import { Trans, t } from '@lingui/macro'
import { useLingui } from '@lingui/react'
import { STAFFING_PERMISSIONS as P } from '@repo/staffing'
import { Alert, AlertDescription } from '@repo/ui/alert'
import {
	AlertDialog,
	AlertDialogCancel,
	AlertDialogContent,
	AlertDialogDescription,
	AlertDialogFooter,
	AlertDialogHeader,
	AlertDialogTitle,
} from '@repo/ui/alert-dialog'
import { Button } from '@repo/ui/button'
import {
	Frame,
	FrameDescription,
	FrameHeader,
	FramePanel,
	FrameTitle,
} from '@repo/ui/frame'
import { useEffect, useState } from 'react'
import { useFetcher } from 'react-router'
import { toast } from 'sonner'
import { useStaffAction } from '#app/hooks/use-staff-action.ts'
import { useStaffClient } from '#app/hooks/use-staff-client.ts'
import {
	assignmentResultSchema,
	pinResultSchema,
	type StaffAssignmentRow,
	type StaffDetail,
} from '#app/utils/staffing/staff-types.ts'
import { PinPanel } from './pin-panel.tsx'
import { ScheduleLinkSection } from './schedule-link-section.tsx'
import { useTeamContext } from './team-context.ts'

type PinIntent = { kind: 'set' | 'remove'; assignment: StaffAssignmentRow }

/**
 * PINs and the optional app login. A PIN is generated by the server and shown
 * once in a panel; nothing here can read an existing PIN, because only a keyed
 * hash is stored. Resetting asks first, since the old PIN stops working at once.
 */
export function AccessTab({
	detail,
	canInvite,
	onChanged,
}: {
	detail: StaffDetail
	canInvite: boolean
	onChanged: () => void
}) {
	const { _, i18n } = useLingui()
	const { client, can } = useStaffClient('staff')
	const { scopes, dataRegion, reloadRoster } = useTeamContext()
	const canWrite = can(P.UPDATE_STAFF) && detail.staff.status !== 'terminated'
	const action = useStaffAction()
	const [shown, setShown] = useState<{
		pin: string
		scopeName: string
	} | null>(null)
	const [intent, setIntent] = useState<PinIntent | null>(null)

	const active = detail.assignments.filter((assignment) => assignment.active)
	const nameOf = (scopeId: string) =>
		scopes.find((scope) => scope.id === scopeId)?.name ?? '–'

	// The PIN must not outlive this tab.
	useEffect(() => () => setShown(null), [])

	async function setPin(assignment: StaffAssignmentRow) {
		const result = await action.run(async () =>
			pinResultSchema.parse(
				await client.request(
					`/${detail.staff.id}/assignments/${assignment.id}/pin`,
					{ method: 'POST', json: {} },
				),
			),
		)
		if (result.ok) {
			setIntent(null)
			setShown({
				pin: result.value.pin,
				scopeName: nameOf(assignment.scopeId),
			})
			reloadRoster()
			onChanged()
		}
	}

	async function removePin(assignment: StaffAssignmentRow) {
		const result = await action.run(async () =>
			assignmentResultSchema.parse(
				await client.request(
					`/${detail.staff.id}/assignments/${assignment.id}/pin`,
					{ method: 'DELETE' },
				),
			),
		)
		if (result.ok) {
			setIntent(null)
			toast.success(_(t`PIN removed.`))
			onChanged()
		}
	}

	return (
		<div className="flex flex-col gap-6">
			<Frame className="w-full" stackedPanels aria-labelledby="pin-heading">
				<FrameHeader>
					<FrameTitle id="pin-heading">
						<Trans>PINs</Trans>
					</FrameTitle>
					<FrameDescription>
						<Trans>
							A PIN lets them clock in on a shared tablet at one workplace. You
							can set a new one, but never read an old one.
						</Trans>
					</FrameDescription>
				</FrameHeader>
				{shown ? (
					<FramePanel>
						<PinPanel
							pin={shown.pin}
							scopeName={shown.scopeName}
							onDone={() => setShown(null)}
						/>
					</FramePanel>
				) : null}
				{active.length === 0 ? (
					<FramePanel>
						<p className="text-muted-foreground text-sm">
							<Trans>Add them to a workplace to give them a PIN.</Trans>
						</p>
					</FramePanel>
				) : (
					active.map((assignment) => {
						const setOn = assignment.pinSetAt
							? new Intl.DateTimeFormat(i18n.locale, {
									dateStyle: 'medium',
								}).format(assignment.pinSetAt)
							: null
						return (
							<FramePanel
								key={assignment.id}
								className="flex items-center justify-between gap-4 px-5 py-3.5"
							>
								<div className="min-w-0 space-y-0.5">
									<div className="text-foreground text-sm">
										{nameOf(assignment.scopeId)}
									</div>
									<p className="text-muted-foreground text-xs">
										{assignment.hasPin ? (
											setOn ? (
												<Trans>PIN set on {setOn}</Trans>
											) : (
												<Trans>PIN set</Trans>
											)
										) : (
											<Trans>No PIN yet</Trans>
										)}
									</p>
								</div>
								{canWrite ? (
									<div className="flex shrink-0 items-center gap-2">
										<Button
											type="button"
											variant="outline"
											size="sm"
											disabled={shown !== null || action.pending}
											onClick={() =>
												assignment.hasPin
													? setIntent({ kind: 'set', assignment })
													: void setPin(assignment)
											}
										>
											{assignment.hasPin ? (
												<Trans>Reset PIN</Trans>
											) : (
												<Trans>Create PIN</Trans>
											)}
										</Button>
										{assignment.hasPin ? (
											<Button
												type="button"
												variant="ghost"
												size="sm"
												disabled={shown !== null || action.pending}
												onClick={() =>
													setIntent({ kind: 'remove', assignment })
												}
											>
												<Trans>Remove PIN</Trans>
											</Button>
										) : null}
									</div>
								) : null}
							</FramePanel>
						)
					})
				)}
				{action.error && !intent ? (
					<FramePanel>
						<Alert variant="destructive">
							<AlertDescription>{action.error}</AlertDescription>
						</Alert>
					</FramePanel>
				) : null}
			</Frame>
			<ScheduleLinkSection
				staffId={detail.staff.id}
				terminated={detail.staff.status === 'terminated'}
			/>
			<LoginSection
				detail={detail}
				canInvite={canInvite && canWrite}
				dataRegion={dataRegion}
			/>

			<AlertDialog
				open={intent !== null}
				onOpenChange={(open) => {
					if (!open && !action.pending) {
						setIntent(null)
						action.reset()
					}
				}}
			>
				<AlertDialogContent>
					<AlertDialogHeader>
						<AlertDialogTitle>
							{intent?.kind === 'remove' ? (
								<Trans>Remove this PIN?</Trans>
							) : (
								<Trans>Reset this PIN?</Trans>
							)}
						</AlertDialogTitle>
						<AlertDialogDescription>
							{intent?.kind === 'remove' ? (
								<Trans>
									They will not be able to clock in at this workplace until you
									create a new PIN.
								</Trans>
							) : (
								<Trans>
									The current PIN stops working right away. You will see the new
									one once.
								</Trans>
							)}
						</AlertDialogDescription>
					</AlertDialogHeader>
					{action.error ? (
						<Alert variant="destructive">
							<AlertDescription>{action.error}</AlertDescription>
						</Alert>
					) : null}
					<AlertDialogFooter>
						<AlertDialogCancel disabled={action.pending}>
							<Trans>Cancel</Trans>
						</AlertDialogCancel>
						<Button
							type="button"
							variant={intent?.kind === 'remove' ? 'destructive' : 'default'}
							disabled={action.pending}
							onClick={() => {
								if (!intent) return
								void (intent.kind === 'remove'
									? removePin(intent.assignment)
									: setPin(intent.assignment))
							}}
						>
							{intent?.kind === 'remove' ? (
								action.pending ? (
									<Trans>Removing…</Trans>
								) : (
									<Trans>Remove PIN</Trans>
								)
							) : action.pending ? (
								<Trans>Resetting…</Trans>
							) : (
								<Trans>Reset PIN</Trans>
							)}
						</Button>
					</AlertDialogFooter>
				</AlertDialogContent>
			</AlertDialog>
		</div>
	)
}

function LoginSection({
	detail,
	canInvite,
	dataRegion,
}: {
	detail: StaffDetail
	canInvite: boolean
	dataRegion: 'us' | 'ksa'
}) {
	const { _ } = useLingui()
	const { orgSlug } = useTeamContext()
	const fetcher = useFetcher<{ ok?: true; error?: string }>()
	const [confirming, setConfirming] = useState(false)
	const email = detail.staff.email
	const pending = fetcher.state !== 'idle'
	const sent = fetcher.data?.ok === true

	// Close the confirm step once the invitation went out.
	useEffect(() => {
		if (fetcher.data?.ok) {
			setConfirming(false)
			toast.success(_(t`Invitation sent.`))
		}
	}, [fetcher.data, _])

	return (
		<Frame className="w-full" aria-labelledby="login-heading">
			<FrameHeader>
				<FrameTitle id="login-heading">
					<Trans>App login</Trans>
				</FrameTitle>
				<FrameDescription>
					{detail.staff.userId ? (
						<Trans>
							They have a login and are a member of your organization.
						</Trans>
					) : (
						<Trans>
							A login is optional. Without one they can still be on the schedule
							and clock in with a PIN.
						</Trans>
					)}
				</FrameDescription>
			</FrameHeader>
			<FramePanel className="flex flex-col gap-3">
				{!detail.staff.userId ? (
					dataRegion === 'ksa' ? (
						<p className="text-muted-foreground text-sm">
							<Trans>
								App invitations are not available for organizations in the Saudi
								region yet.
							</Trans>
						</p>
					) : canInvite && email ? (
						<div className="flex flex-col items-start gap-2">
							<Button
								type="button"
								variant="outline"
								disabled={sent}
								onClick={() => setConfirming(true)}
							>
								{sent ? (
									<Trans>Invitation sent</Trans>
								) : (
									<Trans>Invite to the app</Trans>
								)}
							</Button>
						</div>
					) : canInvite ? (
						<p className="text-muted-foreground text-sm">
							<Trans>Add an email address to invite them to the app.</Trans>
						</p>
					) : null
				) : null}

				<AlertDialog
					open={confirming}
					onOpenChange={(open) => {
						if (!pending) setConfirming(open)
					}}
				>
					<AlertDialogContent>
						<AlertDialogHeader>
							<AlertDialogTitle>
								<Trans>Send an invitation?</Trans>
							</AlertDialogTitle>
							<AlertDialogDescription>
								<Trans>
									We will email {email} a link to create a login. They join as a
									member, without access to staff or pay data. Each person with
									a login counts toward your seats once they accept.
								</Trans>
							</AlertDialogDescription>
						</AlertDialogHeader>
						{fetcher.data?.error ? (
							<Alert variant="destructive">
								<AlertDescription>
									{fetcher.data.error === 'region_not_supported'
										? _(t`Invitations are not available for this organization.`)
										: _(t`The invitation was not sent. Try again.`)}
								</AlertDescription>
							</Alert>
						) : null}
						<AlertDialogFooter>
							<AlertDialogCancel disabled={pending}>
								<Trans>Cancel</Trans>
							</AlertDialogCancel>
							<Button
								type="button"
								disabled={pending}
								onClick={() =>
									void fetcher.submit(
										{ email: email ?? '', staffId: detail.staff.id },
										{
											method: 'post',
											action: `/${orgSlug}/staff/invite`,
										},
									)
								}
							>
								{pending ? (
									<Trans>Sending…</Trans>
								) : (
									<Trans>Send invitation</Trans>
								)}
							</Button>
						</AlertDialogFooter>
					</AlertDialogContent>
				</AlertDialog>
			</FramePanel>
		</Frame>
	)
}
