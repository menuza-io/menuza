/** Named values a message takes (`count` must be a number for the plural forms). */
export type ReservationMessageValues = Record<string, string | number>

export function renderReservationMessage(
	i18n: I18n,
	key: ReservationMessageKey,
	values?: ReservationMessageValues,
): string {
	const descriptor = RESERVATION_MESSAGES[key]
	// The published types accept values only on the string overload; the
	// runtime reads them off the descriptor itself.
	return i18n._(values ? { ...descriptor, values } : descriptor)
}
